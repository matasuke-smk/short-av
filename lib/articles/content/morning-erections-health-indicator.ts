朝勃ちに気づく頻度は、年齢・睡眠・飲酒・疲れなどで日々変わります。年齢とともに減っていくのも自然なことで、「毎朝なければ異常」というものではありません。年代ごとの決まった回数があるわけでもないので、他人と比べる必要もありません。

